#!/usr/bin/env python3
"""Scaffold a new copy-test build for another client from this one (the Lumion build is the reference implementation).

    python scripts/new_client.py tfp --workspace 93 --base https://personal.buzzlead.io --key-env EMAILBISON_API_KEY_TFP \
        --model-campaign 2103 --display "Truck Fall Prevention" [--dest C:/Users/DELL/railway-tfp]

What it does, in order:
  1. git archive HEAD of THIS repo into --dest (default C:/Users/DELL/railway-<name>) and `git init` there. Never touches this repo.
  2. Copies clients/lumion to clients/<name> as the worked example, rewrites the header fields of client.toml (workspace, host, key
     variable, model campaign, display name, database, Slack channel) and removes the Lumion-only spec and tests.
  3. Points scripts/set_railway_vars.py at <name>-web, CLIENT=<name> and the new key variable.
  4. Writes clients/<name>/TODO.md: the files that still carry Lumion's words and must be rewritten for the new client.
The runbook for everything after this is handoffs/COPY-TEST-TEMPLATE.md (copied into the new build). Prints names only, never a secret.
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent

TODO = """# {display}: what still says Lumion and must be rewritten

Generated by scripts/new_client.py. Delete a line when it is done. Order matches handoffs/COPY-TEST-TEMPLATE.md.

- [ ] client.toml: employee_min/max, verticals and [[vertical_defs]], recontact_days, contacts_per_company, copy lengths, slack_channel
- [ ] titles.txt (declared, best first), exclusions.md, icp.md, pitch.md, do_not_contact.txt (at least one line)
- [ ] fit_prompt.txt: the client's misfit-only rule, with {{verticals}} and {{b2b_rule}} placeholders kept
- [ ] copy_rules.toml: client bans, required patterns, forbidden proof points
- [ ] copy_test.toml: the angles, segments and [fill] target (start at 15 for the proof run, raise after sample approval)
- [ ] prompts/<angle>/prompt_research.txt, prompt_email1.txt, prompt_email2.txt: regenerate with scripts/gen_lumion_prompts.py (rename it)
      Model lines: research openai/gpt-oss-120b, emails anthropic/claude-haiku-4.5 (see memory lumion-copy-model-format)
- [ ] school-map.json is Lumion's vertical to school-type map: replace or delete
- [ ] scripts/collect_lumion_history.py and build_lumion_history.py: point at this client's workspace, then rebuild the tier table
- [ ] Railway: new project, Postgres, <name>-web service, variables (scripts/set_railway_vars.py), Slack app from a manifest
"""


def sub(path: Path, pairs: list[tuple[str, str]]) -> None:
    text = path.read_text(encoding="utf-8")
    for old, new in pairs:
        text = text.replace(old, new)
    path.write_text(text, encoding="utf-8")


def set_toml(path: Path, key: str, value: str) -> None:
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(rf"^{re.escape(key)}\s*=.*$", re.MULTILINE)
    line = f"{key} = {value}"
    path.write_text(pattern.sub(lambda _m: line, text, count=1) if pattern.search(text) else text + "\n" + line + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("name", help="short lowercase client name, e.g. tfp")
    ap.add_argument("--workspace", type=int, required=True)
    ap.add_argument("--base", default="https://personal.buzzlead.io")
    ap.add_argument("--key-env", required=True, help="name of the EmailBison key variable in the root .env")
    ap.add_argument("--model-campaign", type=int, required=True)
    ap.add_argument("--display", default=None)
    ap.add_argument("--dest", default=None)
    a = ap.parse_args()
    name = re.sub(r"[^a-z0-9-]", "", a.name.lower())
    display = a.display or name.upper()
    dest = Path(a.dest) if a.dest else Path("C:/Users/DELL") / f"railway-{name}"
    if dest.exists() and any(dest.iterdir()):
        print(f"{dest} already exists and is not empty; refusing to overwrite.")
        return 1
    dest.mkdir(parents=True, exist_ok=True)

    tar = dest / "_src.tar"
    subprocess.run(["git", "archive", "--format=tar", "-o", str(tar), "HEAD"], cwd=HERE, check=True)
    with tarfile.open(tar) as t:
        t.extractall(dest)
    tar.unlink()
    subprocess.run(["git", "init", "-q"], cwd=dest, check=True)

    src, new = dest / "clients" / "lumion", dest / "clients" / name
    shutil.copytree(src, new)
    shutil.rmtree(src)
    shutil.rmtree(new / "spec", ignore_errors=True)
    for f in dest.glob("tests/test_lumion*.py"):
        f.unlink()
    for f in (dest / "slack").glob("lumion-*"):
        f.unlink()

    toml = new / "client.toml"
    set_toml(toml, "display_name", f'"{display}"')
    set_toml(toml, "workspace_id", str(a.workspace))
    set_toml(toml, "emailbison_base", f'"{a.base}"')
    set_toml(toml, "emailbison_key_env", f'"{a.key_env}"')
    set_toml(toml, "model_campaign_id", str(a.model_campaign))
    set_toml(toml, "database", f'"{name}"')
    set_toml(toml, "slack_channel", f'"#{name}-expander"')

    rv = dest / "scripts" / "set_railway_vars.py"
    sub(rv, [("lumion-web", f"{name}-web"), ('"CLIENT": "lumion"', f'"CLIENT": "{name}"'), ("LUMION_EMAIL_BISON_API_KEY", a.key_env),
             ("lumion-web-production", f"{name}-web-production")])
    (new / "TODO.md").write_text(TODO.format(display=display), encoding="utf-8")

    print(f"Scaffolded {dest}")
    print(f"  client folder: clients/{name} (workspace {a.workspace}, key variable {a.key_env}, model campaign {a.model_campaign})")
    print(f"  next: open clients/{name}/TODO.md and handoffs/COPY-TEST-TEMPLATE.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
